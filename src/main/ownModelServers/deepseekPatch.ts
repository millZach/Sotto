import type { OwnServer } from '../../shared/ownModelServers'
import { OWN_SERVER_PLACEHOLDER_KEY, ownModelOutput } from './providerBlock'

/**
 * The `dsh --patch` overlay main generates for DeepSeek Harness from the user's own model servers (ADR-0124,
 * ADR-0136), the way `providerBlock.ts` generates OpenCode's provider block: at every harness start, handed over as
 * a file path, never printed, and a record change makes running processes outdated. One `dsh-llm-pi-ai` route per
 * **keyless** server under the server's own ID, and the ACP entry's provider and model on the first of them, so a
 * session can be made before the thread's own model is set. A keyed server has no route: its key is kept by
 * OpenCode and Sotto has no copy to hand a second provider, so it is not offered here (ADR-0136).
 *
 * The route an overlay declares is `openai-completions` at the server's saved address, with each model's context
 * and output, its thinking as the effort levels the harness offers, and text as its only input — DeepSeek Harness
 * advertised no image input over ACP on either route checked, so none is declared. The base profile's DeepSeek
 * cloud adapters are disabled, so a process started with this overlay cannot reach DeepSeek's cloud at all.
 */

/** The reasoning levels a thinking model declares, least first, each sent on the wire under its own name but `off`. */
export const DEEPSEEK_REASONING_EFFORTS = ['off', 'low', 'high', 'max'] as const
/** The level a thinking model runs at until the user picks another: the official route's own default. */
export const DEEPSEEK_DEFAULT_EFFORT = 'high'

/** The environment variable a server's route reads its key from. A keyless server gets the placeholder in it. */
export function deepseekRouteKeyVariable(serverId: string): string {
  return `SOTTO_OWN_${serverId.toUpperCase().replace(/[^A-Z0-9]/g, '_')}_KEY`
}

/** The key variables a DeepSeek Harness process needs, each holding the placeholder a keyless server ignores. */
export function deepseekRouteKeys(servers: readonly OwnServer[]): Record<string, string> {
  return Object.fromEntries(keylessServers(servers).map(server => [deepseekRouteKeyVariable(server.id), OWN_SERVER_PLACEHOLDER_KEY]))
}

/** The servers DeepSeek Harness can run in this version: the keyless ones (ADR-0136). */
export function keylessServers(servers: readonly OwnServer[]): OwnServer[] {
  return servers.filter(server => !server.keyed)
}

const yaml = (value: string): string => JSON.stringify(value)

/** The overlay's text, or undefined when no keyless server is saved: there is then no model a session could run. */
export function deepseekPatch(servers: readonly OwnServer[]): string | undefined {
  const keyless = keylessServers(servers)
  const first = keyless[0]
  if (!first?.models[0]) return undefined
  const lines: string[] = [
    '# Generated by Sotto from your own model servers. Do not edit; it is rewritten at every start.',
    '- id: llm-deepseek',
    '  disabled: true',
    '',
    '- id: llm-deepseek-account',
    '  disabled: true',
    '',
    '- id: llm-pi-ai',
    "  name: '@deepseek-ai/dsh-llm-pi-ai'",
    '  config:',
    '    providers:',
  ]
  for (const server of keyless) {
    lines.push(
      `      ${yaml(server.id)}:`,
      `        displayName: ${yaml(server.name)}`,
      `        apiKeyEnv: ${yaml(deepseekRouteKeyVariable(server.id))}`,
      '        api: openai-completions',
      `        baseURL: ${yaml(server.address)}`,
      '        models:',
    )
    for (const model of server.models) {
      lines.push(
        `          - id: ${yaml(model.id)}`,
        `            name: ${yaml(model.name)}`,
        `            contextWindow: ${model.context}`,
        `            maxTokens: ${ownModelOutput(model)}`,
        '            input: [text]',
      )
      if (/deepseek/iu.test(`${model.id} ${model.name}`)) lines.push('            compat:', '              thinkingFormat: deepseek')
      if (model.thinking) lines.push('            reasoningEfforts:', '              off:', '              low: low', '              high: high', '              max: max')
      else lines.push('            reasoningEfforts: false')
    }
  }
  lines.push(
    '',
    '- id: acp',
    "  name: '@deepseek-ai/dsh-acp'",
    '  config:',
    `    provider: ${yaml(first.id)}`,
    `    model: ${yaml(first.models[0].id)}`,
    '',
    '- id: agent-default-model',
    "  name: '@deepseek-ai/dsh-agent-default-model'",
    '  config:',
    `    provider: ${yaml(first.id)}`,
    `    model: ${yaml(first.models[0].id)}`,
    '',
  )
  return lines.join('\n')
}
