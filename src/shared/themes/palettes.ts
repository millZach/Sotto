export type ThemeColorRole = (typeof THEME_COLOR_ROLES)[number]
export type ThemeColors = Readonly<Record<ThemeColorRole, string>>
export type ThemeVariants = Readonly<Partial<Record<ThemeAppearance, ThemeColors>>>
export interface ThemeCollection { readonly id: string; readonly label: string }

export interface ThemeDefinition {
  readonly id: string
  readonly label: string
  /** The appearance `colors` paints; `variants` may carry the other one. */
  readonly appearance: ThemeAppearance
  readonly colors: ThemeColors
  readonly variants?: ThemeVariants
  /** Groups related imported variants into one library card. */
  readonly collection?: ThemeCollection
  /** Generated from the guided editor's background and accent. */
  readonly managed?: boolean
}

