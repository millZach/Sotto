/** One path per letter for each frame, built once: painting a frame only sets eight `d` attributes. */
const paths = new Map<LardoFrame, Readonly<Record<LardoLetter, string>>>()
export function lardoPaths(frame: LardoFrame): Readonly<Record<LardoLetter, string>> {
  let built = paths.get(frame)
  if (!built) {
    const rows = LARDO_FRAMES[frame]
    built = Object.fromEntries(LARDO_LETTERS.map(letter => [letter, pixelPath(rows, letter) || EMPTY])) as Record<LardoLetter, string>
    paths.set(frame, built)
  }
  return built
}
