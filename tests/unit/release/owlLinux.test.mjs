const roots = [], sourceCommit = 'a'.repeat(40), version = '0.1.38-owl.20261021.1', linuxInputs = 'c'.repeat(64)
const names = owlLinuxFileNames(version)
afterEach(async () => { await Promise.all(roots.splice(0).map(root => rm(root, { recursive: true, force: true }))) })
async function directory() { const root = await mkdtemp(join(tmpdir(), 'sotto-owl-linux-test-')); roots.push(root); return root }

/** Stands in for libarchive's tar, so these run on any runner: writes the app.asar the tarball would hold. */
const fakeExtract = ({ source = sourceCommit, packagedVersion = version, inputs = linuxInputs } = {}) => async (_tarball, into, { folder }) => {
  const asar = join(into, folder, 'resources', 'app.asar')
  await owlAppAsar(asar, { sourceCommit: source, version: packagedVersion, buildInputsRevision: inputs })
  return asar
}
const pkginfo = (pkgver = `${names.pkgver}-1`, pkgname = 'sotto-bin') => `# Generated by makepkg\npkgname = ${pkgname}\npkgbase = sotto-bin\npkgver = ${pkgver}\narch = x86_64\n`
const fakePkginfo = text => async () => text
/** Stands in for reading /opt/sotto/resources/app.asar out of the pacman package; `extra` makes the same app's bytes differ. */
const fakePackageExtract = ({ source = sourceCommit, packagedVersion = version, inputs = linuxInputs, extra } = {}) => async (_package, into) => {
  const asar = join(into, 'opt', 'sotto', 'resources', 'app.asar')
  await owlAppAsar(asar, { sourceCommit: source, version: packagedVersion, buildInputsRevision: inputs })
  if (extra !== undefined) await appendFile(asar, extra)
  return asar
}
const fakes = (options = {}) => ({ extractAsar: fakeExtract(options.asar), extractPackageAsar: fakePackageExtract(options.packageAsar ?? options.asar),
  readPkginfo: fakePkginfo(options.pkginfo ?? pkginfo()) })

/** The folder `gh run download` leaves: both receipts and every file they list. */
async function linuxFolder({ packageReceipt = receipt => receipt, pacmanReceipt = receipt => receipt, bodies: change = bodies => bodies } = {}) {
  const root = await directory(), folder = join(root, 'linux'); await mkdir(folder)
  const bodies = change({
    tarball: 'tarball bytes', pacman: 'pacman bytes',
    pkgbuild: `pkgname=sotto-bin\npkgver=${names.pkgver}\npkgrel=1\n_version="${version}"\n`,
    srcinfo: `pkgbase = sotto-bin\n\tpkgver = ${names.pkgver}\n\tpkgrel = 1\n`,
  })
  const entry = async role => {
    await writeFile(join(folder, names[role]), bodies[role])
    const bytes = await readFile(join(folder, names[role]))
    return { filename: names[role], size: bytes.length, sha256: sha256(bytes) }
  }
  const tarball = await entry('tarball')
  const files = { pacman: await entry('pacman'), pkgbuild: await entry('pkgbuild'), srcinfo: await entry('srcinfo') }
  await writeFile(join(folder, names.packageReceipt), JSON.stringify(packageReceipt({ kind: 'sotto-owl-linux-package', schemaVersion: 1, version, track: 'owl',
    platform: 'linux', arch: 'x64', sourceCommit, buildInputsRevision: linuxInputs, files: { tarball } })))
  await writeFile(join(folder, names.pacmanReceipt), JSON.stringify(pacmanReceipt({ kind: 'sotto-owl-linux-pacman', schemaVersion: 1, version, pkgver: names.pkgver,
    pkgrel: 1, track: 'owl', platform: 'linux', arch: 'x64', sourceCommit, tarball: { filename: tarball.filename, sha256: tarball.sha256 }, files })))
  return { root, folder }
}

describe('Linux Owl files from the workflow run', () => {
  it('accepts the receipts\' files and returns the tarball and pacman package to attach', async () => {
    const { folder } = await linuxFolder()
    const result = await verifyOwlLinuxArtifacts(folder, { version, sourceCommit }, fakes())
    expect(result).toMatchObject({ version, sourceCommit, pkgver: '0.1.38owl.20261021.1', buildInputsRevision: linuxInputs })
    expect(result.files.map(file => [file.role, file.filename])).toEqual([['tarball', names.tarball], ['pacman', names.pacman]])
    expect(result.files[0].sha256).toBe(sha256('tarball bytes'))
  })
  it.each([
    ['another Owl version', { packageReceipt: receipt => ({ ...receipt, version: '0.1.38-owl.20261021.2' }) }, 'not the Windows Owl'],
    ['another source', { packageReceipt: receipt => ({ ...receipt, sourceCommit: 'b'.repeat(40) }) }, 'different source commit'],
    ['a pacman receipt for another Owl', { pacmanReceipt: receipt => ({ ...receipt, version: '0.1.38-owl.20261021.2' }) }, 'not the Windows Owl'],
    ['a pacman receipt for another source', { pacmanReceipt: receipt => ({ ...receipt, sourceCommit: 'b'.repeat(40) }) }, 'different source commit'],
    ['a package built from another tarball', { pacmanReceipt: receipt => ({ ...receipt, tarball: { ...receipt.tarball, sha256: 'e'.repeat(64) } }) }, 'different tarball'],
    ['the wrong pacman version', { pacmanReceipt: receipt => ({ ...receipt, pkgver: '0.1.38' }) }, 'pacman version'],
    ['a receipt for another platform', { packageReceipt: receipt => ({ ...receipt, platform: 'darwin' }) }, 'x64 Linux Owl'],
    ['an extra listed file', { pacmanReceipt: receipt => ({ ...receipt, files: { ...receipt.files, extra: receipt.files.pacman } }) }, 'nothing else'],
    ['an escaping file name', { packageReceipt: receipt => ({ ...receipt, files: { tarball: { ...receipt.files.tarball, filename: '../escape.tar.gz' } } }) }, 'invalid entry'],
  ])('refuses %s', async (_, change, message) => {
    const { folder } = await linuxFolder(change)
    await expect(verifyOwlLinuxArtifacts(folder, { version, sourceCommit }, fakes())).rejects.toThrow(message)
  })
  it('refuses bytes that differ from a receipt, and files no receipt lists', async () => {
    const changed = await linuxFolder()
    await writeFile(join(changed.folder, names.pacman), 'pacman byteZ')
    await expect(verifyOwlLinuxArtifacts(changed.folder, { version, sourceCommit }, fakes())).rejects.toThrow(`${names.pacman} does not match its Linux Owl receipt`)
    const tarball = await linuxFolder()
    await writeFile(join(tarball.folder, names.tarball), 'tarball byteZ')
    await expect(verifyOwlLinuxArtifacts(tarball.folder, { version, sourceCommit }, fakes())).rejects.toThrow('does not match')
    const extra = await linuxFolder()
    await writeFile(join(extra.folder, 'notes.txt'), 'stray')
    await expect(verifyOwlLinuxArtifacts(extra.folder, { version, sourceCommit }, fakes())).rejects.toThrow('must hold only')
  })
  it.each([
    [{ asar: { source: 'b'.repeat(40) } }, 'different source commit'],
    [{ asar: { packagedVersion: '0.1.38' } }, 'not 0.1.38-owl'],
    [{ asar: { inputs: 'e'.repeat(64) } }, 'build inputs differ'],
    [{ pkginfo: pkginfo('0.1.38-1') }, 'is not sotto-bin 0.1.38owl.20261021.1-1'],
    [{ pkginfo: pkginfo(`${names.pkgver}-2`) }, 'is not sotto-bin'],
    [{ pkginfo: pkginfo(`${names.pkgver}-1`, 'sotto-owl-bin') }, 'is not sotto-bin'],
  ])('refuses a tarball or package whose contents disagree: %j', async (options, message) => {
    const { folder } = await linuxFolder()
    await expect(verifyOwlLinuxArtifacts(folder, { version, sourceCommit }, fakes(options))).rejects.toThrow(message)
  })
  it('refuses a recipe that names another version, even with receipts that match it', async () => {
    const { folder } = await linuxFolder({ bodies: bodies => ({ ...bodies, pkgbuild: bodies.pkgbuild.replace(`pkgver=${names.pkgver}`, 'pkgver=0.1.38') }) })
    await expect(verifyOwlLinuxArtifacts(folder, { version, sourceCommit }, fakes())).rejects.toThrow('PKGBUILD or .SRCINFO does not name this Owl')
  })
  // Two runs of the same Owl version from different sources: run A's good tarball beside run B's package, with the
  // pacman receipt edited to claim A's source and tarball. Both files would pass the repository's attestation check.
  it('refuses a same-version package built from another source, though its receipt claims the verified tarball', async () => {
    const { folder } = await linuxFolder()
    await expect(verifyOwlLinuxArtifacts(folder, { version, sourceCommit }, fakes({ packageAsar: { source: 'b'.repeat(40) } })))
      .rejects.toThrow('pacman package\'s app was built from a different source commit')
    await expect(verifyOwlLinuxArtifacts(folder, { version, sourceCommit }, fakes({ packageAsar: { inputs: 'e'.repeat(64) } })))
      .rejects.toThrow('pacman package\'s app build inputs differ')
    await expect(verifyOwlLinuxArtifacts(folder, { version, sourceCommit }, fakes({ packageAsar: { packagedVersion: '0.1.38-owl.20261021.2' } })))
      .rejects.toThrow('pacman package\'s app is version 0.1.38-owl.20261021.2')
  })
  it('refuses a package whose app differs from the tarball\'s by a single byte, even with matching provenance', async () => {
    const { folder } = await linuxFolder()
    await expect(verifyOwlLinuxArtifacts(folder, { version, sourceCommit }, fakes({ packageAsar: { extra: '\n' } })))
      .rejects.toThrow('carries a different app from the verified tarball')
  })
  it('refuses an altered pacman receipt even when the package carries the tarball\'s app', async () => {
    for (const [change, message] of [
      [receipt => ({ ...receipt, sourceCommit: 'b'.repeat(40) }), 'different source commit'],
      [receipt => ({ ...receipt, tarball: { ...receipt.tarball, sha256: 'e'.repeat(64) } }), 'different tarball'],
      [receipt => ({ ...receipt, files: { ...receipt.files, pacman: { ...receipt.files.pacman, sha256: 'e'.repeat(64) } } }), 'does not match its Linux Owl receipt'],
    ]) {
      const { folder } = await linuxFolder({ pacmanReceipt: change })
      await expect(verifyOwlLinuxArtifacts(folder, { version, sourceCommit }, fakes())).rejects.toThrow(message)
    }
  })
  // Windows 11's tar is libarchive with gzip and zstd, the release machine's tools.
  it.runIf(process.platform === 'win32')('reads app.asar from a real tarball, and .PKGINFO and app.asar from a real zstd package', async () => {
    const tar = zipReadingTar(), root = await directory(), stage = join(root, 'stage')
    await owlAppAsar(join(stage, names.tarballFolder, 'resources', 'app.asar'), { sourceCommit, version, buildInputsRevision: linuxInputs })
    await writeFile(join(stage, names.tarballFolder, 'sotto'), 'executable')
    execFileSync(tar, ['-czf', names.tarball, '-C', 'stage', names.tarballFolder], { cwd: root, windowsHide: true })
    await mkdir(join(root, 'package')); await writeFile(join(root, 'package', '.PKGINFO'), pkginfo())
    await owlAppAsar(join(root, 'package', 'opt', 'sotto', 'resources', 'app.asar'), { sourceCommit, version, buildInputsRevision: linuxInputs })
    await writeFile(join(root, 'package', 'opt', 'sotto', 'sotto'), 'executable')
    execFileSync(tar, ['--zstd', '-cf', names.pacman, '-C', 'package', '.PKGINFO', 'opt'], { cwd: root, windowsHide: true })
    const into = join(root, 'into'); await mkdir(into)
    const asar = await extractLinuxAppAsar(join(root, names.tarball), into, { folder: names.tarballFolder })
    expect(basename(asar)).toBe('app.asar')
    expect(await readPacmanPkginfo(join(root, names.pacman))).toBe(pkginfo())
    const installed = join(root, 'installed'); await mkdir(installed)
    const packageAsar = await extractPacmanAppAsar(join(root, names.pacman), installed)
    expect(await readFile(packageAsar)).toEqual(await readFile(asar))
    // Only the one named entry comes out.
    expect(await readdir(join(installed, 'opt', 'sotto'), { recursive: true })).toEqual(['resources', join('resources', 'app.asar')])
    execFileSync(tar, ['--zstd', '-cf', 'empty.pkg.tar.zst', '-C', 'package', '.PKGINFO'], { cwd: root, windowsHide: true })
    await expect(extractPacmanAppAsar(join(root, 'empty.pkg.tar.zst'), installed)).rejects.toThrow('exactly one /opt/sotto/resources/app.asar')
    await writeFile(join(stage, 'stray.txt'), 'beside the app')
    execFileSync(tar, ['-czf', 'stray.tar.gz', '-C', 'stage', names.tarballFolder, 'stray.txt'], { cwd: root, windowsHide: true })
    await expect(extractLinuxAppAsar(join(root, 'stray.tar.gz'), into, { folder: names.tarballFolder })).rejects.toThrow(`hold only ${names.tarballFolder}`)
  })
})

describe('Owl publication with the Linux files', () => {
  async function fixture() {
    const linux = await linuxFolder(), release = join(linux.root, 'release'); await mkdir(release)
    for (const [path, body] of [[`Sotto-Owl-Setup-${version}.exe`, 'installer'], [`Sotto-Owl-Setup-${version}.exe.blockmap`, 'blockmap'], ['owl.yml', 'owl feed']]) await writeFile(join(release, path), body)
    const provenance = { sourceCommit, buildInputsRevision: 'windows-inventory' }
    return { ...linux, rootDirectory: linux.root, desktop: async () => ({ version, provenance, packagedProvenance: provenance }), checkout: () => ({ sourceCommit, clean: true }),
      inputsRevision: async () => 'windows-inventory', verifyLinux: (folder, expected) => verifyOwlLinuxArtifacts(folder, expected, fakes()) }
  }
  it('takes the downloaded folder once, beside the Mac folder', () => {
    expect(owlPublicationArguments(['--linux-artifacts', 'linux', '--mac-artifacts', 'mac'])).toEqual({ notesFile: undefined, hostArchives: [], macArtifacts: 'mac', linuxArtifacts: 'linux' })
    expect(() => owlPublicationArguments(['--linux-artifacts', 'one', '--linux-artifacts', 'two'])).toThrow('Usage')
    expect(() => owlPublicationArguments(['--linux-artifacts'])).toThrow('Supply a path')
  })
  it('attaches the tarball and pacman package after checking their attestations, and lists them in the checksums', async () => {
    const setup = await fixture(), result = await prepareOwlRelease({ ...setup, args: ['--linux-artifacts', 'linux'] })
    const attached = result.files.map(file => basename(file))
    expect(attached).toEqual([`Sotto-Owl-Setup-${version}.exe`, `Sotto-Owl-Setup-${version}.exe.blockmap`, 'owl.yml', names.tarball, names.pacman])
    expect(result.sums.map(line => line.split('  ')[1])).toEqual(attached)
    expect((await readFile(join(setup.root, 'release', 'SHA256SUMS.txt'), 'utf8')).trim().split('\n')).toEqual(result.sums)
    const stop = "; if ($LASTEXITCODE -ne 0) { throw 'The Linux Owl build attestation did not verify. Nothing was published.' }"
    const [tarballCheck, pacmanCheck, create] = result.commands[0].split(`${stop}; `)
    expect(`${tarballCheck}${stop}`).toBe(`gh attestation verify '${join(setup.folder, names.tarball)}' --repo millZach/Sotto${stop}`)
    expect(`${pacmanCheck}${stop}`).toBe(`gh attestation verify '${join(setup.folder, names.pacman)}' --repo millZach/Sotto${stop}`)
    expect(create).toMatch(/^gh release create /u); expect(create).toContain('--prerelease --latest=false')
    for (const kept of ['PKGBUILD', '.SRCINFO', names.packageReceipt, names.pacmanReceipt]) expect(result.commands.join('\n')).not.toContain(join(setup.folder, kept))
    expect(result.commands[1]).toContain('SHA256SUMS.txt')
    const notes = await readFile(join(setup.root, 'release', 'owl-notes.md'), 'utf8')
    expect(notes).toContain('Windows and Linux (Omarchy, x64)'); expect(notes).toContain('sudo pacman -U')
    expect(notes).toContain('Installing a stable sotto-bin package returns to stable'); expect(notes).toContain(`Source commit: ${sourceCommit}`)
  })
  it('names every platform in the notes when Mac and Linux files are both attached, and keeps the Mac notes unchanged', () => {
    const both = defaultOwlNotes({ mac: true, linux: true })
    expect(both).toMatch(/^A preview of the next Sotto for Windows, Apple silicon Macs and Linux \(Omarchy, x64\)\./u)
    expect(both).toContain('notarized by Apple'); expect(both).toContain('sudo pacman -U')
    expect(defaultOwlNotes({ mac: true })).not.toContain('Linux')
    expect(defaultOwlNotes({ mac: true }).startsWith('A preview of the next Sotto for Windows and Apple silicon Macs.')).toBe(true)
    expect(defaultOwlNotes()).toBe('Windows preview. Installs over Sotto and shares its data. Owl features are available in this build.')
  })
  it('refuses Linux files for another version or source before writing publication files', async () => {
    for (const change of [receipt => ({ ...receipt, version: '0.1.38-owl.20261021.2' }), receipt => ({ ...receipt, sourceCommit: 'b'.repeat(40) })]) {
      const setup = await fixture()
      const other = await linuxFolder({ packageReceipt: change })
      await expect(prepareOwlRelease({ ...setup, args: ['--linux-artifacts', other.folder] })).rejects.toThrow('Linux Owl packaging receipt')
      await expect(readFile(join(setup.root, 'release', 'owl-notes.md'))).rejects.toMatchObject({ code: 'ENOENT' })
    }
  })
  it('refuses a Linux file that changes after its verification', async () => {
    const setup = await fixture()
    const verifyLinux = async (folder, expected) => {
      const verified = await setup.verifyLinux(folder, expected)
      await writeFile(join(folder, names.pacman), 'replaced after verification')
      return verified
    }
    await expect(prepareOwlRelease({ ...setup, verifyLinux, args: ['--linux-artifacts', 'linux'] })).rejects.toThrow('changed after its release verification')
  })
})
