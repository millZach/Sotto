//! Reads Sotto's real theme roles out of `src/renderer/src/styles/tokens.css`
//! and writes them as a Rust table, so the prototype's colours come from the
//! same file the Electron window paints from (ADR-0011). The derived `--tt-*`
//! tokens are computed from these roles in `src/theme.rs`, mirroring the CSS.

use std::{env, fs, path::PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let tokens = manifest.join("../src/renderer/src/styles/tokens.css");
    println!("cargo:rerun-if-changed={}", tokens.display());
    let css = fs::read_to_string(&tokens).expect("tokens.css is readable");

    let dark = block(&css, ":root {");
    let light = block(&css, ":root[data-theme='light'] {");
    let sotto_dark = block(&css, ":root[data-theme='dark'][data-theme-id='t3-code'] {");
    let sotto_dark_canvas = block(
        &css,
        ":root[data-theme='dark'][data-theme-id='t3-code'] .app-shell:not(:has(.watcher-room)) {",
    );

    let mut out = String::new();
    out.push_str("// Generated by build.rs from src/renderer/src/styles/tokens.css. Do not edit.\n");
    for (name, body, prefix) in [
        ("DARK_ROLES", &dark, "--theme-"),
        ("LIGHT_ROLES", &light, "--theme-"),
        ("SOTTO_DARK_LITERALS", &sotto_dark, "--tt-"),
        ("SOTTO_DARK_CANVAS", &sotto_dark_canvas, "--tt-"),
    ] {
        let entries = oklch_entries(body, prefix);
        assert!(!entries.is_empty(), "no oklch entries found for {name}");
        out.push_str(&format!("pub const {name}: &[(&str, f32, f32, f32)] = &[\n"));
        for (key, l, c, h) in entries {
            out.push_str(&format!("    (\"{key}\", {l:?}, {c:?}, {h:?}),\n"));
        }
        out.push_str("];\n");
    }
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("theme_roles.rs");
    fs::write(dest, out).unwrap();

    // A 16 MB main-thread stack. Windows gives 1 MB by default; a debug build under GPUI's
    // hot patching overflowed it on the first patch.
    if std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc") {
        println!("cargo:rustc-link-arg-bins=/STACK:16777216");
    }
}

/// The text between the opening brace that follows `selector` and its closing brace.
fn block(css: &str, selector: &str) -> String {
    let start = css
        .find(selector)
        .unwrap_or_else(|| panic!("selector not found in tokens.css: {selector}"))
        + selector.len();
    let end = start + css[start..].find('}').expect("block closes");
    css[start..end].to_string()
}

/// Every `--name: oklch(L C H);` declaration in a block whose name starts with `prefix`.
fn oklch_entries(body: &str, prefix: &str) -> Vec<(String, f32, f32, f32)> {
    let mut entries = Vec::new();
    for line in body.lines() {
        let line = line.trim();
        let Some(rest) = line.strip_prefix(prefix) else { continue };
        let Some((name, value)) = rest.split_once(':') else { continue };
        let value = value.trim().trim_end_matches(';').trim();
        let Some(inner) = value.strip_prefix("oklch(").and_then(|v| v.strip_suffix(')')) else {
            continue;
        };
        let parts: Vec<f32> = inner.split_whitespace().filter_map(|p| p.parse().ok()).collect();
        if parts.len() == 3 {
            entries.push((name.trim().to_string(), parts[0], parts[1], parts[2]));
        }
    }
    entries
}
